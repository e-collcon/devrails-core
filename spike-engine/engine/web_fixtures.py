"""
Engine-generated dashboard fixtures for the web-app (TASK-020, BR-37), Contract v1.3.

Every synced document here is produced by run_once() on a FixtureSource, so
the web-app renders exactly what the engine would write. Each entry carries
`as_of`, the instant the dashboard should treat as "now" when deriving A.9
states (Pending / Sync Delayed / Stale depend on elapsed time).
"""

from __future__ import annotations

import json
from datetime import datetime, timedelta
from pathlib import Path

from config import Settings
from engine import clock
from engine.feed_store import MemoryFeedStore
from engine.fixtures import SCENARIOS, FixtureSource
from engine.payload import stub_document
from engine.run import run_once

AS_OF = clock.parse_iso_utc("2026-10-25T19:55:00Z")  # Sun 25 Oct, 12:55 PDT
GCP_PROJECT = "devrails-poc-target"
UID = "fixture-uid"
SETTINGS = Settings(gcp_project_id=GCP_PROJECT, uid=UID, project_id=GCP_PROJECT, quota_project_id="devrails-core-dev")


def _synced(scenario: str, poll_at: datetime) -> tuple[MemoryFeedStore, dict]:
    hours = SCENARIOS[scenario].history_hours or 24 * 24
    store = MemoryFeedStore()
    store.create_stub_if_absent(UID, GCP_PROJECT, stub_document(GCP_PROJECT, poll_at - timedelta(hours=hours)))
    result = run_once(SETTINGS, FixtureSource(scenario), store, now=poll_at)
    if result.exit_code != 0:
        raise RuntimeError(f"fixture {scenario} failed: {result.outcome} {result.errors}")
    return store, result.document


def build_states() -> dict:
    states: dict[str, dict] = {}

    def entry(label, doc, note=""):
        return {"label": label, "as_of": clock.iso_utc(AS_OF), "note": note, "doc": doc}

    states["no_project"] = entry("No configured project", None, "Document absent (A.3)")
    states["pending"] = entry("First sync pending", stub_document(GCP_PROJECT, AS_OF - timedelta(minutes=3)),
                              "Stub, 3 min after provisioning")
    states["sync_delayed"] = entry("Initial sync delayed", stub_document(GCP_PROJECT, AS_OF - timedelta(minutes=30)),
                                   "Stub, 30 min after provisioning (frontend-derived)")

    poll = AS_OF - timedelta(minutes=4)
    for key, label in [
        ("normal", "Normal"),
        ("insufficient_history", "Normal · first day"),
        ("empty", "Normal · no recent activity"),
        ("rising", "Elevated · runs out in ~5 days"),
        ("elevated", "Elevated · past 75 %"),
        ("risky", "Risky · storage over the allowance"),
        ("runs_out_soon", "Risky · runs out in ~30 h"),
    ]:
        _, doc = _synced(key, poll)
        states["no_activity" if key == "empty" else key] = entry(label, doc, SCENARIOS[key].description)

    # Sync Failed: last success 20 min ago, the latest poll failed (A.8). Within the 30-min
    # stale window, so A.9 renders Sync Failed rather than Stale.
    store, _ = _synced("normal", AS_OF - timedelta(minutes=20))
    failed = run_once(SETTINGS, FixtureSource("failing"), store, now=AS_OF)
    assert failed.exit_code == 1
    states["sync_failed"] = entry("Sync failed", store.get(UID, GCP_PROJECT),
                                  "Last success 20 min ago; the latest poll could not reach the project")

    # Stale: backend silent for 100 min (A.9 #5, D4 = 30 min recommended).
    _, doc = _synced("normal", AS_OF - timedelta(minutes=100))
    states["stale"] = entry("Stale", doc, "No successful sync for 100 min")
    return states


def export_web_fixtures(out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "dashboard-feed.json"
    payload = {
        "_comment": "Generated by `python spike-engine/main.py export-fixtures`. Do not edit by hand.",
        "contract": "Firestore Data Contract v1.3",
        "states": build_states(),
    }
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path
